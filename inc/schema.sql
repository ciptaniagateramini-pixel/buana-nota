CREATE TABLE IF NOT EXISTS users(
  id INT AUTO_INCREMENT PRIMARY KEY, nama VARCHAR(60) NOT NULL UNIQUE, pin_hash VARCHAR(255) NOT NULL,
  role ENUM('admin','petugas') NOT NULL DEFAULT 'petugas', aktif TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sessions(
  token_hash CHAR(64) PRIMARY KEY, user_id INT NOT NULL, expires DATETIME NOT NULL, ua VARCHAR(200),
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, KEY(user_id), KEY(expires)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS counters(name VARCHAR(60) PRIMARY KEY, val INT NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS orders(
  id INT AUTO_INCREMENT PRIMARY KEY, no_order VARCHAR(30) NOT NULL UNIQUE,
  nama VARCHAR(120) NOT NULL, kontak VARCHAR(40) NOT NULL, email VARCHAR(120) NOT NULL DEFAULT '', alamat TEXT NOT NULL,
  items_asli MEDIUMTEXT NOT NULL,
  status ENUM('Masuk','Nota terbit','Surat jalan terbit','Selesai','Batal') NOT NULL DEFAULT 'Masuk',
  bayar ENUM('Belum bayar','DP','Lunas') NOT NULL DEFAULT 'Belum bayar',
  diskon DECIMAL(14,2) NOT NULL DEFAULT 0, ongkir DECIMAL(14,2) NOT NULL DEFAULT 0,
  no_nota VARCHAR(30) NULL UNIQUE, tgl_nota DATETIME NULL, nota_oleh INT NULL,
  no_sj VARCHAR(30) NULL UNIQUE, tgl_sj DATETIME NULL, sj_oleh INT NULL, driver VARCHAR(80) NULL, plat VARCHAR(20) NULL,
  ip VARCHAR(45) NOT NULL DEFAULT '', created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY(status), KEY(created_at), KEY(tgl_nota), KEY(ip,created_at)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS order_items(
  id INT AUTO_INCREMENT PRIMARY KEY, order_id INT NOT NULL, urut INT NOT NULL DEFAULT 0,
  nama VARCHAR(200) NOT NULL, qty DECIMAL(12,2) NOT NULL, satuan VARCHAR(20) NOT NULL, ket VARCHAR(200) NOT NULL DEFAULT '',
  harga DECIMAL(14,2) NOT NULL DEFAULT 0, KEY(order_id)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS log(
  id INT AUTO_INCREMENT PRIMARY KEY, order_id INT NULL, user_id INT NULL, aksi VARCHAR(40) NOT NULL, detail VARCHAR(500) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, KEY(order_id)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS login_fail(ip VARCHAR(45) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, KEY(ip,created_at)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
